#!/usr/bin/env python3
"""Finalised evidence evaluation for v2, Tasks 1 and 2 ONLY.

RISK NOTES (Task 3) ARE OUT OF SCOPE and are not scored here. They have no
human-annotated evidence spans -- the target is free prose generated by a
teacher model -- so a span-based evidence metric is undefined for them. This is
stated rather than silently omitted.

Everything is rescored OFFLINE from archived v2 predictions. No inference, no
retraining, no v1 numbers or v1 data. v1 was read for METRIC DEFINITIONS only,
and where a v1 definition is questionable it is flagged rather than copied
(see TOKEN-LEVEL F1 below).

--------------------------------------------------------------------------
NORMALIZATION AND TOKENIZATION (the v2 pipeline's established rule)
--------------------------------------------------------------------------
norm(s) = " ".join(s.lower().split())   [v1_contractnli/text_norm.py, shared]
tokens(s) = norm(s).split()             -- whitespace tokens of the normalized
                                           string. No stemming, no punctuation
                                           stripping, no subword tokenizer.
This is the same normalizer used by the strict metric and by _grounded, so the
strict and diagnostic numbers are computed over identical text.

--------------------------------------------------------------------------
PRIMARY METRIC (unchanged) -- strict example-level containment
--------------------------------------------------------------------------
Per example, with gold spans G and predicted spans P:
  hay   = norm(" ".join(P))
  cover = [norm(g) in hay for g in G]      (substring, contiguous)
  TP : G non-empty AND all(cover)
  FN : G non-empty AND not all(cover)
  FP : G empty     AND P non-empty
  TN : G empty     AND P empty
  F1 = 2TP / (2TP + FP + FN)
Multiple/discontinuous gold spans: ALL must be covered; the predicted spans are
concatenated first, so a gold span may be satisfied by text spanning what the
model emitted as two separate spans. One miss fails the whole example.

--------------------------------------------------------------------------
DIAGNOSTIC 1 -- token-level F1
--------------------------------------------------------------------------
Over the UNION of spans per example: gold bag = tokens of all gold spans
concatenated; pred bag likewise. Intersection by MULTISET (min of counts).
  P = |intersection| / |pred bag|
  R = |intersection| / |gold bag|
  F1 = harmonic mean
Reported as a mean over gold-bearing examples.

DEPARTURE FROM v1, DELIBERATE: v1's token_overlap uses SET intersection, which
discards repetition. Standard token-level F1 (SQuAD, Rajpurkar et al. 2016)
uses multiset intersection. A contract clause repeats common tokens heavily, so
the two differ materially. Multiset is used here as primary and the set-based
variant is ALSO reported, labelled, so v1 and v2 figures appearing in the same
deck can be compared like with like.

--------------------------------------------------------------------------
DIAGNOSTIC 2 -- span-level recall at Jaccard >= 0.5
--------------------------------------------------------------------------
Jaccard is computed on token SETS (that is what Jaccard means):
  J(g,p) = |set(g) & set(p)| / |set(g) | set(p)|

SPAN MATCHING RULE -- GREEDY ONE-TO-ONE. Stated explicitly because the choice
changes the number:
  * all (gold, pred) pairs are scored, sorted by J descending, and accepted
    while J >= 0.5 and NEITHER span is already matched
  * one predicted span may satisfy AT MOST ONE gold span
  * multiple predicted spans may NOT be combined to satisfy one gold span
  * matching is therefore one-to-one, not many-to-many
Rationale: a many-to-many rule lets a single over-long predicted span "locate"
every gold span at once, which rewards exactly the over-extraction this project
identified as the commercial failure mode. The cost is that one-to-one is
CONSERVATIVE for a model that splits one clause into two predicted spans; that
case is counted as one located gold span, not two. Same rule for both tasks.

The 0.5 threshold is fixed, not tuned. See the report for what is and is not
claimed about its provenance.

--------------------------------------------------------------------------
STRICT-FAILURE DECOMPOSITION
--------------------------------------------------------------------------
For examples that are strict failures (G non-empty, containment failed):
  boundary_only : every gold span located at J >= 0.5 -- right region, wrong edges
  partial       : some but not all gold spans located
  not_found     : no gold span located
"""
import sys, json, argparse
from pathlib import Path
from collections import Counter, defaultdict

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "v1_contractnli"))
from text_norm import norm                                     # noqa: E402
from doc_harness import parse_output, strip_wrappers, _find_json  # noqa: E402

JACCARD_T = 0.5


def toks(s):
    return norm(s).split()


def jaccard(a, b):
    A, B = set(toks(a)), set(toks(b))
    if not A or not B:
        return 0.0
    return len(A & B) / len(A | B)


def token_f1(gold, pred, multiset=True):
    g = Counter(toks(" ".join(gold))) if multiset else set(toks(" ".join(gold)))
    p = Counter(toks(" ".join(pred))) if multiset else set(toks(" ".join(pred)))
    ng = sum(g.values()) if multiset else len(g)
    npd = sum(p.values()) if multiset else len(p)
    if ng == 0 or npd == 0:
        return 0.0, 0.0, 0.0
    inter = sum((g & p).values()) if multiset else len(g & p)
    P, R = inter / npd, inter / ng
    return (2 * P * R / (P + R) if P + R else 0.0), P, R


def match_spans(gold, pred):
    """Greedy one-to-one. -> (n_located, [(gi,pj,J)])"""
    pairs = sorted(((jaccard(g, p), gi, pj)
                    for gi, g in enumerate(gold) for pj, p in enumerate(pred)),
                   key=lambda x: -x[0])
    ug, up, out = set(), set(), []
    for j, gi, pj in pairs:
        if j < JACCARD_T:
            break
        if gi in ug or pj in up:
            continue
        ug.add(gi); up.add(pj); out.append((gi, pj, j))
    return len(ug), out


def strict_case(gold, pred):
    if gold:
        hay = norm(" ".join(pred))
        cov = [bool(norm(g)) and norm(g) in hay for g in gold]
        return ("TP" if all(cov) else "FN"), sum(cov) / len(cov)
    return ("FP" if pred else "TN"), 1.0


def f1_from(tp, fp, fn):
    P = tp / (tp + fp) if tp + fp else 0.0
    R = tp / (tp + fn) if tp + fn else 0.0
    return (2 * P * R / (P + R) if P + R else 0.0), P, R


def cuad_parse(raw):
    t = strip_wrappers(raw)
    if not t:
        return None, []
    d = _find_json(t)
    if not isinstance(d, dict) or "present" not in d:
        return None, []
    ev = d.get("evidence") or []
    return bool(d["present"]), ([str(x) for x in ev] if isinstance(ev, list) else [])


def evidence_block(items):
    """items: list of (gold_spans, pred_spans). -> metric dict."""
    case = Counter()
    tf = tp_ = tr_ = 0.0
    sf = 0.0
    n_soft = 0
    gold_total = located_total = 0
    dec = Counter()
    for gold, pred in items:
        c, _ = strict_case(gold, pred)
        case[c] += 1
        if not gold:
            continue
        n_soft += 1
        f, P, R = token_f1(gold, pred, multiset=True)
        tf += f; tp_ += P; tr_ += R
        sf += token_f1(gold, pred, multiset=False)[0]
        nloc, _ = match_spans(gold, pred)
        gold_total += len(gold); located_total += nloc
        if c == "FN":
            dec["boundary_only" if nloc == len(gold) else
                "partial" if nloc else "not_found"] += 1
    f1, P, R = f1_from(case["TP"], case["FP"], case["FN"])
    return {
        "n_examples": sum(case.values()),
        "n_gold_bearing": n_soft,
        "strict_f1": f1, "strict_precision": P, "strict_recall": R,
        "strict_TP": case["TP"], "strict_FP": case["FP"],
        "strict_FN": case["FN"], "strict_TN": case["TN"],
        "strict_successes": case["TP"], "strict_failures": case["FN"],
        "token_f1_multiset": tf / n_soft if n_soft else 0.0,
        "token_precision": tp_ / n_soft if n_soft else 0.0,
        "token_recall": tr_ / n_soft if n_soft else 0.0,
        "token_f1_setbased_v1style": sf / n_soft if n_soft else 0.0,
        "span_recall_j50": located_total / gold_total if gold_total else 0.0,
        "gold_spans_total": gold_total, "gold_spans_located": located_total,
        "strict_failure_decomposition": dict(dec),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", required=True)
    ap.add_argument("--tag", required=True)
    ap.add_argument("--visibility", default="v2/_a_visibility.json")
    ap.add_argument("--lengths",
                    default="/scratch/ibi761/legalai/v2_results/cost__q4_3task_win.json")
    ap.add_argument("--out-dir", default="v2/evidence_eval")
    args = ap.parse_args()

    recs = [json.loads(l) for l in open(args.raw, encoding="utf-8")]
    out = {"tag": args.tag, "source_predictions": args.raw,
           "jaccard_threshold": JACCARD_T,
           "span_matching": "greedy one-to-one",
           "token_f1_intersection": "multiset (SQuAD-style); set-based also reported",
           "task3_risknote": "OUT OF SCOPE -- no annotated evidence spans exist "
                             "for synthetic risk notes; no evidence metric is "
                             "defined or reported for them"}

    # ---------------- Task 1 ----------------
    t1 = [r for r in recs if r["task"] == "contractnli"]
    if t1:
        items = []
        for r in t1:
            d = parse_output(r["raw"])
            items.append((r["gold_evidence"], d["evidence"]))
        out["task1_contractnli"] = evidence_block(items)

    # ---------------- Task 2 ----------------
    t2 = [r for r in recs if r["task"] == "cuad"]
    if t2:
        items, bycat, present_cnt = [], defaultdict(list), Counter()
        cls = Counter()
        for r in t2:
            p, ev = cuad_parse(r["raw"])
            p = bool(p)
            items.append((r["gold_evidence"], ev))
            bycat[r["category"]].append((r["gold_evidence"], ev))
            g = bool(r["present"])
            cls["tp" if (g and p) else "fp" if (p and not g) else
                "fn" if (g and not p) else "tn"] += 1
            present_cnt[r["category"]] += int(g)
        blk = evidence_block(items)
        pf, pp, pr = f1_from(cls["tp"], cls["fp"], cls["fn"])
        n = sum(cls.values()); n_pres = cls["tp"] + cls["fn"]
        blk["present_class"] = {
            "precision": pp, "recall": pr, "f1": pf,
            "accuracy": (cls["tp"] + cls["tn"]) / n,
            "CONSTANT_ABSENT_BASELINE_measured": (n - n_pres) / n,
            "present_rate": n_pres / n,
            "tp": cls["tp"], "fp": cls["fp"], "fn": cls["fn"], "tn": cls["tn"]}
        # per category
        vis = json.load(open(args.visibility)) if Path(args.visibility).exists() else None
        percat = {}
        for c, its in sorted(bycat.items()):
            b = evidence_block(its)
            e = {"n": len(its), "n_present": present_cnt[c],
                 "strict_f1": b["strict_f1"],
                 "token_f1": b["token_f1_multiset"],
                 "span_recall_j50": b["span_recall_j50"],
                 "gold_spans": b["gold_spans_total"]}
            if vis and c in vis.get("by_category", {}):
                v = vis["by_category"][c]
                tot = v.get("visible", 0) + v.get("invisible", 0)
                e["truncation_ceiling_span_level"] = (v.get("visible", 0) / tot
                                                      if tot else None)
                e["spans_invisible"] = v.get("invisible", 0)
            percat[c] = e
        blk["per_category"] = percat
        if vis:
            blk["truncation_ceiling_overall"] = {
                "span_level": vis["span_visibility"],
                "spans_total": vis["spans_total"],
                "spans_visible": vis["spans_visible"],
                "spans_invisible": vis["spans_invisible"],
                "row_level": vis["rows_fully_visible"] / vis["rows_with_evidence"],
                "rows_with_evidence": vis["rows_with_evidence"],
                "rows_with_an_invisible_span": vis["rows_with_invisible_span"]}
        # length stratification
        if Path(args.lengths).exists():
            clen = json.load(open(args.lengths))["contract_tokens"]
            buck = defaultdict(list)
            for r, it in zip(t2, items):
                L = clen.get(r["contract"])
                if L is None:
                    continue
                k = "<16K" if L < 16000 else "16-32K" if L < 32000 else ">32K"
                buck[k].append(it)
            blk["by_contract_length"] = {
                k: {**{a: b for a, b in evidence_block(v).items()
                       if a in ("n_examples", "n_gold_bearing", "strict_f1",
                                "token_f1_multiset", "span_recall_j50",
                                "gold_spans_total")},
                    "n_contracts_bucket": None}
                for k, v in buck.items()}
        out["task2_cuad"] = blk

    outd = Path(args.out_dir); outd.mkdir(parents=True, exist_ok=True)
    fp = outd / f"evidence__{args.tag}.json"
    json.dump(out, open(fp, "w"), indent=2)
    print(f"-> {fp}")
    for k in ("task1_contractnli", "task2_cuad"):
        if k not in out:
            continue
        b = out[k]
        print(f"\n{k}")
        for a in ("n_examples", "n_gold_bearing", "strict_f1", "strict_TP",
                  "strict_FN", "strict_FP", "strict_TN", "token_f1_multiset",
                  "token_precision", "token_recall", "token_f1_setbased_v1style",
                  "span_recall_j50", "gold_spans_total", "gold_spans_located",
                  "strict_failure_decomposition"):
            print(f"  {a:30s} {b[a]}")


if __name__ == "__main__":
    main()
